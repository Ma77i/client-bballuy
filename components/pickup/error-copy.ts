export function errorText(message: string | undefined): string | undefined {
  if (!message) return message;
  if (message.includes('\n')) return message.split('\n').map(line => errorText(line)).join('\n');
  if (messages[message]) return messages[message];
  const count = message.match(/^Choose (\d+)–(\d+) players, including you if playing\.$/);
  if (count) return `Elegí entre ${count[1]} y ${count[2]} participantes, incluyéndote si jugás.`;
  if (/^(Unable|Invalid|Choose|Enter|Please|Your |This |The |Use |Fill |Refresh|Sign in|Game |Match |Player )/.test(message))
    return 'No pudimos completar la comprobación. Revisá los datos y reintentá la acción indicada.';
  return message;
}
